// Bakes the dot-matrix world map used by components/InteractiveWorldMap.tsx.
//
// Downloads Natural Earth 1:110m land + country outlines (world-atlas TopoJSON),
// samples a regular lon/lat grid in an equirectangular projection, and writes
// one compact SVG path per layer to lib/world-map-dots.ts so the page ships no
// geo libraries and does no work at runtime.
//
//   node scripts/build-world-map.mjs

import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(root, 'lib', 'world-map-dots.ts');

// Projection window — keep in sync with the constants written to the output.
const WIDTH = 1000;
const LAT_TOP = 83;
const LAT_BOTTOM = -57;
const LON_LEFT = -170;
const LON_RIGHT = 190;
const SCALE = WIDTH / (LON_RIGHT - LON_LEFT);
const HEIGHT = Math.round((LAT_TOP - LAT_BOTTOM) * SCALE);
const STEP = 6.5; // px between dot centres

const HIGHLIGHT = { uk: '826', sa: '682' }; // ISO 3166-1 numeric

const CDN = 'https://cdn.jsdelivr.net/npm/world-atlas@2';

async function load(name) {
  const res = await fetch(`${CDN}/${name}`);
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
  return res.json();
}

/** Decode a TopoJSON topology's arcs into absolute [lon, lat] arrays. */
function decodeArcs(topo) {
  const { scale, translate } = topo.transform;
  return topo.arcs.map((arc) => {
    let x = 0;
    let y = 0;
    return arc.map(([dx, dy]) => {
      x += dx;
      y += dy;
      return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
    });
  });
}

function ring(arcs, indexes) {
  const pts = [];
  for (const i of indexes) {
    const arc = i < 0 ? arcs[~i].slice().reverse() : arcs[i];
    pts.push(...(pts.length ? arc.slice(1) : arc));
  }
  return pts;
}

/** All rings of a Polygon / MultiPolygon geometry (holes included — even-odd handles them). */
function rings(arcs, geom) {
  if (geom.type === 'Polygon') return geom.arcs.map((r) => ring(arcs, r));
  if (geom.type === 'MultiPolygon') return geom.arcs.flatMap((p) => p.map((r) => ring(arcs, r)));
  if (geom.type === 'GeometryCollection') return geom.geometries.flatMap((g) => rings(arcs, g));
  return [];
}

function withBBox(rs) {
  return rs.map((pts) => {
    let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
    for (const [x, y] of pts) {
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
    return { pts, minX, minY, maxX, maxY };
  });
}

function inside(rs, lon, lat) {
  let hit = false;
  for (const r of rs) {
    if (lon < r.minX || lon > r.maxX || lat < r.minY || lat > r.maxY) continue;
    const p = r.pts;
    for (let i = 0, j = p.length - 1; i < p.length; j = i++) {
      const [xi, yi] = p[i];
      const [xj, yj] = p[j];
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
    }
  }
  return hit;
}

const [landTopo, countryTopo] = await Promise.all([load('land-110m.json'), load('countries-110m.json')]);

const land = withBBox(rings(decodeArcs(landTopo), landTopo.objects.land));
const countryArcs = decodeArcs(countryTopo);
const countryRings = Object.fromEntries(
  Object.entries(HIGHLIGHT).map(([key, id]) => {
    const geom = countryTopo.objects.countries.geometries.find((g) => g.id === id);
    if (!geom) throw new Error(`country ${id} not found`);
    return [key, withBBox(rings(countryArcs, geom))];
  })
);

const layers = { land: [], uk: [], sa: [] };
const fmt = (n) => +n.toFixed(1);

for (let y = STEP / 2; y < HEIGHT; y += STEP) {
  const lat = LAT_TOP - y / SCALE;
  // Offset alternate rows for a hex-ish texture that reads less like graph paper.
  const shift = (Math.round(y / STEP) % 2) * (STEP / 2);
  for (let x = STEP / 2 + shift; x < WIDTH; x += STEP) {
    let lon = LON_LEFT + x / SCALE;
    if (lon > 180) lon -= 360;
    const hub = Object.keys(countryRings).find((k) => inside(countryRings[k], lon, lat));
    if (hub) layers[hub].push([x, y]);
    else if (inside(land, lon, lat)) layers.land.push([x, y]);
  }
}

// Small countries can fall between grid points; guarantee each hub a visible cluster.
for (const key of Object.keys(countryRings)) {
  if (layers[key].length < 4) console.warn(`warning: only ${layers[key].length} dots for ${key}`);
}

// "M x yh0" draws a zero-length segment; with round caps each becomes a dot.
const toPath = (pts) => pts.map(([x, y]) => `M${fmt(x)} ${fmt(y)}h0`).join('');

const src = `// Generated by scripts/build-world-map.mjs — do not edit by hand.
// Natural Earth 1:110m via world-atlas, equirectangular, ${STEP}px dot grid.

export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${HEIGHT};
export const MAP_DOT_STEP = ${STEP};

const LAT_TOP = ${LAT_TOP};
const LON_LEFT = ${LON_LEFT};
const SCALE = ${SCALE};

/** Project a real-world coordinate onto the map's viewBox. */
export function project(lat: number, lng: number): { x: number; y: number } {
  let lon = lng;
  if (lon < LON_LEFT) lon += 360;
  return { x: (lon - LON_LEFT) * SCALE, y: (LAT_TOP - lat) * SCALE };
}

export const LAND_DOTS = ${JSON.stringify(toPath(layers.land))};

export const COUNTRY_DOTS: Record<'uk' | 'sa', string> = {
  uk: ${JSON.stringify(toPath(layers.uk))},
  sa: ${JSON.stringify(toPath(layers.sa))}
};
`;

await writeFile(OUT, src);
console.log(
  `wrote ${path.relative(root, OUT)} — ${WIDTH}x${HEIGHT}, land ${layers.land.length}, uk ${layers.uk.length}, sa ${layers.sa.length} dots, ${(src.length / 1024).toFixed(1)} KB`
);
